// Интерфейс AXI-Stream. Реализована поддержка сигналов
// TVALID, TREADY, TDATA, TID, TLAST.

//  --------------------- Важно! --------------------
// | Во избежание параметризации интерфейса ширина   |
// | шин фиксируется в максимально возможном значе-  |
// | нии. Такой подход называется maximum footprint. |
//  --------------------- Важно! --------------------

//  --------------------- Важно! --------------------
// | Ширина данных могла быть "захардкожена" числом. |
// | В некоторых guides именно такой подход и ис-    |
// | пользуется. Автор же советует создавать define  |
// | для подобных констант, чтобы можно было переоп- |
// | ределить его из командной строки в крайнем слу- |
// | чае. Единственное замечание - выбирайте доста-  |
// | точно уникальное имя define (например, добав-   |
// | ляйте префикс в виде имени модуля, для которо-  |
// | го создается интерфейс), т.к. иначе имена мо-   |
// | гут "конфликтовать" при использовании несколь-  |
// | ких интерфейсов в одном проекте.                |
//  --------------------- Важно! --------------------

interface axis_intf(input logic aclk, input logic aresetn);

    logic                  tvalid;
    logic                  tready;
    axis_pkg::axis_tdata_t tdata;
    axis_pkg::axis_tid_t   tid;
    logic                  tlast;

endinterface
