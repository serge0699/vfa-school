`timescale 1ns/1ps

module tb_fulladder_sync;

    // Импорт универсальных компонентов и объектов.
    // Нужен для использования ~common_resource_db~.
    import common_pkg::*;

    // Импорт компонентов и объектов сумматора.
    import fulladder_sync_dv_pkg::*;

    // Параметр для периода тактового сигнала.
    parameter CLK_PERIOD = 10;

    // Объявление тактового сигнала и сигнала сброса.
    logic clk_i;
    logic areset_i;

    // Объявление интерфейса последовательностного сумматора.

    //  -------------------- Важно! --------------------
    // | Тактовый сигнал и сигнал сброса подключаются   |
    // | к интерфейсу через порты интерфейса.           |
    //  -------------------- Важно! --------------------

    fulladder_sync_intf intf(clk_i, areset_i);

    // Подключение тестируемого модуля.

    //  -------------------- Важно! --------------------
    // | Сигналы кроме тактового и сброса подключаются  |
    // | к интерфейсу иерархически.                     |
    //  -------------------- Важно! --------------------

    fulladder_sync DUT (
        .clk_i    ( clk_i     ), 
        .areset_i ( areset_i  ), 
        .A_i      ( intf.A    ), 
        .B_i      ( intf.B    ), 
        .Cin_i    ( intf.Cin  ), 
        .Cout_o   ( intf.Cout ), 
        .S_o      ( intf.S    )
    );

    // Генерация тактового сигнала.
    initial begin
        clk_i <= 1'b0;
        forever begin
            #(CLK_PERIOD/2) clk_i = ~clk_i;
        end
    end

    // Генерация сигнала сброса.
    initial begin
        areset_i <= 1'b1;
        @(posedge clk_i);
        @(negedge clk_i);
        areset_i = 1'b0;
    end


    // Процесс создания драйвера и монитора, а также
    // их совместного запуска.

    //  ------------------------- Важно! -------------------------
    // | Обратите внимание на то, что ссылка на статический       |
    // | интерфейс  помещается в базу ресурсов при помощи:        |
    // | common_resource_db#(virtual fulladder_sync_intf)::set(). |
    // | Ссылка на интерфейс будет получена компонентами в ходе   |
    // | их конфигурации при помощи метода ~build()~.             |
    //  ------------------------- Важно! -------------------------

    initial begin
        
        // Создание компонентов.

        //  ---------------------------- Важно! ----------------------------
        // | Построение полного иерарического имени компонента опре-        |
        // | деляется в классе common_component, от которого насле-         |
        // | дованы driver и monitor. В данном примере полные имена         |
        // | будут равны "drv" и "mon". См. common/dv/common_component.sv   |
        //  ---------------------------- Важно! ----------------------------

        automatic fulladder_sync_driver  drv = new("drv", null);
        automatic fulladder_sync_monitor mon = new("mon", null);

        // Передача ссылки на статический интерфейс в базу ресурсов.

        //  ---------------------------- Важно! ----------------------------
        // | При отправке в базу ресурсов ключ формируется из конкатенации  |
        // | первого и второго аргументов метода ~set()~. См реализацию в   |
        // | файле common/dv/common_resource_db. Отладку базы ресурсов мож- |
        // | но активировать при помощи флага симуляции +common_db_debug.   |
        // | Ключами в базе ресурсов будут "drv.vif" и "mon.vif".           |
        // | При помощи этих ключей driver и monitor смогут "забрать" из    |
        // | базы ссылки на интерфейс, т.к. в функции ~get()~ ключ формиру- |
        // | ется из конкатенации первого и второго аргументов. Для класса  |
        // | driver конкатенация {get_full_name(), ".", "vif"} будет равна  |
        // | "drv.vif". Для monitor эта же конкатенация будет равна         |
        // | "mon.vif". Обратите внимание, что при таком подходе ключ опре- |
        // | деляется ие-рархией окружения.                                 |
        //  ---------------------------- Важно! ----------------------------

        common_resource_db#(virtual fulladder_sync_intf)::set(
            "drv", "vif", intf);
        common_resource_db#(virtual fulladder_sync_intf)::set(
            "mon", "vif", intf);

        // Сборка и запуск компонентов.
        drv.build();
        mon.build();
        fork
            drv.run();
            mon.run();
        join_none
        wait(areset_i === 1'b0);
        repeat(10) @(posedge clk_i);
        disable fork;
        $finish();

    end

endmodule
