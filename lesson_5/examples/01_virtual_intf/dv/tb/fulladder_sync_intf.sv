// Интерфейс последовательностного сумматора.
// Имеет два входных порта: тактового сигнала
// и сигнала сброса.

//  --------------------- Важно! ---------------------
// | Единственное преимущество портов перед объяв-    |
// | лением в теле интерфейса состоит в том, что      |
// | они могут подключены в конструкции объявления    |
// | интерфейса, например:                            |
// |     ~fulladder_sync_intf intf(clk_i, areset_i);~ |
// | Недостатком же является необходимость объявля-   |
// | ть направление портов.                           |
// | Итог: все провода, кроме тактового сигнала и     |
// |       сигнала сброса объявляются в теле интер-   |
// |       фейса.                                     |
//  --------------------- Важно! ---------------------

interface fulladder_sync_intf(input logic clk, input logic areset);

    logic A;
    logic B;
    logic Cin;
    logic Cout;
    logic S;

endinterface
