// Базовый (родительский) класс
// с полем ~addr~ и методом ~print()~.
class base;
    rand bit [31:0] addr;
    function void print();
        $display("addr %h", addr);
    endfunction
endclass

// Наследованный класс с иной
// имплементацией метода ~print()~
// и новым полем ~mode~.
class child extends base;
    rand bit mode;
    function void print();
        $display("addr %h with mode %1b",
            addr, mode);
    endfunction
endclass

module tb_classes;

    // Object handle родительского
    // и наследованного типов.
    base  b1;
    child c1, c2;

    initial begin

        // Создание объекта наследованного
        // типа.
        c1 = new();

        // Создание объекта родительского
        // типа.
        b1 = new();

        // Upcasting. Теперь родительский
        // handle указывает на объект
        // наследованного типа.
        b1 = c1;

        // Downcasting. Используется системная
        // функция/задача $cast(), вызов которой
        // выполняется в ходе симуляции.
        // Функция возвращает 1 или 0 в зави-
        // симости от успешности или неуспеш-
        // ности и не вызывает ошибки во время
        // симуляции. Задача в случае неуспеш-
        // ности генерирует ошибку в ходе симу-
        // ляции. На стадии компиляции типы
        // переменных, передаваемых в $cast(),
        // не проверяются.
        // В примере ниже вызывается задача
        // $cast().

        //  -------------------- Важно! -------------------
        // | Проверка типов не производится на этапе ком-  |
        // | пиляции, т.к. $cast() предназначен для при-   |
        // | ведения типов, которые могут быть потенциаль- |
        // | но несовместимы. Примеры применения $cast(),  |
        // | приближенные к реальности, будут представлены |
        // | в других примерах.                            |
        //  -------------------- Важно! -------------------

        //  -------------------- Важно! -------------------
        // | Симуляторы при неуспешности $cast() формируют |
        // | ошибку. Часть симуляторов могут дополнительно |
        // | завершить симуляцию.                          |
        //  -------------------- Важно! -------------------

        $cast(c2, b1);

        // В данном примере $cast() завершится успешно,
        // вызов ~print()~ приведет к выполнению реализации
        // наследованного класса.
        c2.print();

        // Через object handle наследованного класса
        // доступ разрешен как к элементам, определен-
        // ным в родительском классе, так и к элемен-
        // там, определенным в наследованном классе.
        $display("addr: %h", c2.addr);
        $display("mode: %1b", c2.mode);

    end

endmodule
