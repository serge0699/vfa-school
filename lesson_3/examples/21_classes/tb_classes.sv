// Объявление класса с полем ~a~
// типа bit [7:0] и методом ~print()~.
// Обратите внимание, что у поля ~a~
// есть ключевое слово rand, которое
// позволяет полю принимать случайное
// значение при вызове randomize()
// для объекта класса.
class base;

    rand bit [7:0] a;

    function void print();
        $display("base: %0d", a);
    endfunction
        
endclass

// Объекты классов рандомизируются при
// помощи встроенной функции randomize().
// Функция возвращает 0 или 1 в зависимости
// от успешности рандомизации. В данном
// примере вызов "обернут" в void'(),
// чтобы дать симулятору "понять", что
// результат рандомизации не представляет
// интереса и не будет никак использован
// далее. В данном примере это допустимо,
// т.к. никаких ограничений не накладывается
// (как и в части следующих примеров), так
// что рандомизация в любом случае завершится
// успешно.
module tb_classes;

    base b1;

    initial begin
        b1 = new();
        repeat(5) begin
            void'(b1.randomize());
            b1.print();
        end
    end

endmodule
