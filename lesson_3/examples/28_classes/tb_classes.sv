// Одно из возможных выражений для
// ограничений - dist. Оно
// определяет вероятность ран-
// домизации значений для поля.
// Обратите внимание на комм-
// ментарий ниже и подумайте,
// почему вероятности именно
// такие. В комментарии к модулю
// ниже будет дано пояснение.
class base;

    rand bit [7:0] addr;
    rand bit [7:0] data;

    constraint addr_c {
        addr dist {
                0  := 10, //  0: вероятность     10/(2+10) = 10/12 = 30/36
            [5:10] :/ 2   //  5: вероятность  (2/6)/(2+10) =  2/72 =  1/36
                          //  6: вероятность  (2/6)/(2+10) =  2/72 =  1/36
                          //  7: вероятность  (2/6)/(2+10) =  2/72 =  1/36
                          //  8: вероятность  (2/6)/(2+10) =  2/72 =  1/36
                          //  9: вероятность  (2/6)/(2+10) =  2/72 =  1/36
                          // 10: вероятность  (2/6)/(2+10) =  2/72 =  1/36
        };};

endclass

// При использовании dist вес, написанный
// после оператора :/ равномерно распреде-
// ляется между значениями, написанными
// до него. В анном примере вес 10 присва-
// ивается значению 0, вес 2 распределяется
// между значениями 5, 6, 7, 8, 9, 10. То
// есть вес каждого значения 2/6 (6 - ко-
// личество значений в интервале).
// Суммарный вес: 10 (для 0) + 2 (для
// всех элементов интервала) = 12. Вероят-
// ность рандомизации значения равно отно-
// шению его веса к суммарному весу всех
// значений (включая вес самого значения).
// Таким образом, вероятность рандомизации
// значения 0 в 30 раз выше чем какого-либо
// значения из интервала [5:10].
module tb_classes;

    base b1;

    initial begin
        b1 = new();
        repeat(10) begin
            void'(b1.randomize());
            $display("addr: %0d, data: %0d", b1.addr, b1.data);
        end
    end

endmodule
