// Одно из возможных выражений для
// ограничений - dist. Оно
// определяет вероятность ран-
// домизации значений для поля.
// Обратите внимание на комм-
// ментарий ниже и подумайте,
// почему вероятности именно
// такие. В комментарии к модулю
// ниже будет дано пояснение.
class base;

    rand bit [7:0] addr;
    rand bit [7:0] data;

    constraint addr_c {
        addr dist {
                0  := 10, //  0: вероятность 10/(6*2+10) = 10/22
            [5:10] := 2   //  5: вероятность  2/(6*2+10) =  2/22
                          //  6: вероятность  2/(6*2+10) =  2/22
                          //  7: вероятность  2/(6*2+10) =  2/22
                          //  8: вероятность  2/(6*2+10) =  2/22
                          //  9: вероятность  2/(6*2+10) =  2/22
                          // 10: вероятность  2/(6*2+10) =  2/22
        };};

endclass

// При использовании dist вес, написанный
// после оператора := присваивается каж-
// дому элементу, написанному до него. В
// данном примере вес 10 присваивается зна-
// чению 0, вес 2 присваивается значениям
// 5, 6, 7, 8, 9 и 10 (т.к.) указан интервал.
// Суммарный вес: 10 (для 0) + 6 * 2 (для
// всех элементов интервала) = 22. Вероят-
// ность рандомизации значения равно отно-
// шению его веса к суммарному весу всех
// значений (включая вес самого значения).
// Таким образом, вероятность рандомизации
// значения 0 в 5 раз выше чем какого-либо
// значения из интервала [5:10].
module tb_classes;

    base b1;

    initial begin
        b1 = new();
        repeat(10) begin
            void'(b1.randomize());
            $display("addr: %0d, data: %0d", b1.addr, b1.data);
        end
    end

endmodule
